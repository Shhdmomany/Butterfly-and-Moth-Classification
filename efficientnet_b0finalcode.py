def evaluate_model(model, data_loader, criterion):
    model.eval()

    total_loss = 0.0
    correct = 0
    total = 0

    with torch.no_grad():
      #Loops through batches of images and labels from the validation/test loader.
        for images, labels in data_loader:
            images = images.to(device)
            labels = labels.to(device)

            outputs = model(images)
            loss = criterion(outputs, labels)

            total_loss += loss.item()

            _, predicted = torch.max(outputs, 1)
#Adds the number of images in this batch to the total count.
            total += labels.size(0)
            correct += (predicted == labels).sum().item()

    avg_loss = total_loss / len(data_loader)
    accuracy = 100 * correct / total

    return avg_loss, accuracy

def train_experiment(
    model,
    train_loader,
    val_loader,
    test_loader,
    lr,
    momentum,
    epochs,
    weight_decay,
    combination_name
):

    criterion = nn.CrossEntropyLoss()

    optimizer = optim.SGD(
        model.parameters(),
        lr=lr,
        momentum=momentum,
        weight_decay=weight_decay
    )

    epoch_results = []

    start_time = time.time()

    for epoch in range(epochs):

        model.train()

        train_loss_total = 0.0
        train_correct = 0
        train_total = 0

        for images, labels in train_loader:
            images = images.to(device)
            labels = labels.to(device)

            optimizer.zero_grad()

            outputs = model(images)
            loss = criterion(outputs, labels)

            loss.backward()
            #learning step
            optimizer.step()

            train_loss_total += loss.item()

            _, predicted = torch.max(outputs, 1)

            train_total += labels.size(0)
            train_correct += (predicted == labels).sum().item()

        train_loss = train_loss_total / len(train_loader)
        train_acc = 100 * train_correct / train_total

        val_loss, val_acc = evaluate_model(model, val_loader, criterion)
        test_loss, test_acc = evaluate_model(model, test_loader, criterion)

        elapsed_time = time.time() - start_time

        print(
            f"{combination_name} | "
            f"Epoch [{epoch+1}/{epochs}] | "
            f"Train Loss: {train_loss:.4f} | "
            f"Train Acc: {train_acc:.2f}% | "
            f"Val Loss: {val_loss:.4f} | "
            f"Val Acc: {val_acc:.2f}% | "
            f"Test Loss: {test_loss:.4f} | "
            f"Test Acc: {test_acc:.2f}%"
        )

        epoch_results.append({
            "Combination": combination_name,
            "Epoch": epoch + 1,
            "Train Loss": train_loss,
            "Train Accuracy (%)": train_acc,
            "Validation Loss": val_loss,
            "Validation Accuracy (%)": val_acc,
            "Test Loss": test_loss,
            "Test Accuracy (%)": test_acc,
            "Elapsed Time (seconds)": elapsed_time
        })

    total_training_time = time.time() - start_time

    return epoch_results, total_training_time

