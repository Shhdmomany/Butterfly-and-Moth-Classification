# ================= PREDICTION FUNCTION =================
def predict_image(model_name, image):

    image = image.convert("RGB")

    if model_name == "AlexNet":
        selected_model = model_alex

    elif model_name == "Custom CNN":
        selected_model = cnn_model

    elif model_name == "ResNet18":
        selected_model = resnet_model

    elif model_name == "EfficientNet-B0":
        selected_model = model_eff

    image_tensor = interface_transform(image).unsqueeze(0).to(device)

    with torch.no_grad():

        outputs = selected_model(image_tensor)

        predicted = torch.argmax(outputs, dim=1).item()

    predicted_class = class_names[predicted]

    return image, predicted_class

